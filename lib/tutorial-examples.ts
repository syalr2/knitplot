function makeDocument(input: {
  name: string;
  rows: string[];
  colors: string[];
  technique: ChartDocument["instructions"]["technique"];
  patternUse: ChartDocument["instructions"]["patternUse"];
  trimBackground: boolean;
}) {
  const palette = input.colors.map((hex, index) => ({
    id: `example-${input.name.toLowerCase().replace(/\s+/g, "-")}-${index}`,
    hex,
  }));
  return {
    name: input.name,
    width: input.rows[0].length,
    height: input.rows.length,
    gaugeStitches: 20,
    gaugeRows: 24,
    gaugeMeasure: 10,
    gaugeUnit: "cm" as const,
    instructions: {
      ...defaultInstructionSettings,
      technique: input.technique,
      patternUse: input.patternUse,
      trimBackground: input.trimBackground,
    },
    guides: {
      symmetry: "none" as const,
      showRepeatGuides: false,
      repeatWidth: input.rows[0].length,
      repeatHeight: input.rows.length,
    },
    palette,
    cells: input.rows.map((row) =>
      Array.from(row, (character) => palette[Number(character)].id),
    ),
  };
}

